// Generates supabase/seed.sql from tenants/<slug>/business.json for the demo studios.
// The seed creates the studios in PREVIEW, demo owner accounts (local only) and clearly marked demo
// bookings/payments so the cabinet and statistics have something to show. Images are added by
// `pnpm tenant:publish <slug>` afterwards (Storage cannot be filled from SQL).
//   pnpm seed:generate
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { z } from 'zod';
import { businessSchema, toPublishConfig } from './lib/business-schema.ts';
import { ROOT, isMain, log } from './lib/env.ts';
import { loadBusiness } from './lib/tenant-files.ts';

export const DEMO_TENANTS = [
  { slug: 'ngx-detailing', owner: 'owner+ngx@example.com', password: 'demo-ngx-2026' },
  { slug: 'tork-service', owner: 'owner+tork@example.com', password: 'demo-tork-2026' },
];

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

function tenantSql(slug: string, owner: string, password: string): string {
  const res = loadBusiness(slug);
  if (!res.ok || !res.business) throw new Error(`${slug}: ${res.errors.join('; ')}`);
  const b = res.business;
  const cfg = toPublishConfig(b);
  return `
-- ===================================================================== ${b.name} (demo)
select app.ensure_tenant(${q(b.slug)}, ${q(b.name)}, ${q(b.shortName)}, ${q(b.timezone)});
select app.publish_tenant(${q(JSON.stringify(cfg))}::jsonb, '{}'::jsonb, false);

-- Demo owner (LOCAL/DEMO ONLY — never run this seed against production).
select app.add_member((select id from public.tenants where slug = ${q(b.slug)}), seed_demo.owner(${q(owner)}, ${q(password)}), 'owner');

select seed_demo.bookings(${q(b.slug)});
`;
}

const HEADER = `-- GENERATED by scripts/generate-seed.ts from tenants/*/business.json — do not edit by hand.
-- Demo data for local development and previews. All bookings created here are is_demo = true
-- (the studios are in preview), and are removed automatically when a studio goes live.

create schema if not exists seed_demo;

-- Demo bookings spread over the past week and the next days, with statuses and payments,
-- so the cabinet, the week view and the statistics show realistic numbers.
-- Demo owner account. Works on a real Supabase stack (fills GoTrue columns + identity) and on bare Postgres.
create or replace function seed_demo.owner(p_email text, p_password text) returns uuid language plpgsql as $$
declare
  uid uuid;
begin
  select id into uid from auth.users where email = p_email;
  if uid is not null then
    return uid;
  end if;
  uid := gen_random_uuid();
  insert into auth.users (id, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data)
  values (uid, p_email, extensions.crypt(p_password, extensions.gen_salt('bf')), now(),
          '{"provider":"email","providers":["email"]}'::jsonb, '{}'::jsonb);
  if exists (select 1 from information_schema.columns where table_schema = 'auth' and table_name = 'users' and column_name = 'aud') then
    execute $q$update auth.users set instance_id = '00000000-0000-0000-0000-000000000000', aud = 'authenticated',
              role = 'authenticated', confirmation_token = '', recovery_token = '', email_change_token_new = '', email_change = ''
            where id = $1$q$ using uid;
  end if;
  if to_regclass('auth.identities') is not null then
    execute $q$insert into auth.identities (id, user_id, provider_id, identity_data, provider, created_at, updated_at, last_sign_in_at)
              values (gen_random_uuid(), $1, $1::text, jsonb_build_object('sub', $1::text, 'email', $2, 'email_verified', true),
                      'email', now(), now(), now())$q$ using uid, p_email;
  end if;
  return uid;
end;
$$;

create or replace function seed_demo.bookings(p_slug text) returns void language plpgsql as $$
declare
  t public.tenants;
  svc public.services;
  names text[] := array['Алексей', 'Мария', 'Дмитрий', 'Ольга', 'Сергей', 'Анна', 'Игорь', 'Елена', 'Павел', 'Наталья'];
  cars text[] := array['Kia Rio', 'Toyota Camry', 'BMW X5', 'Hyundai Solaris', 'Mazda CX-5', 'Lada Vesta', 'Skoda Octavia', 'VW Tiguan', 'Haval Jolion', 'Geely Monjaro'];
  i int := 0;
  d int;
  hh int;
  res jsonb;
  bid uuid;
  start timestamptz;
begin
  select * into t from public.tenants where slug = p_slug;
  if exists (select 1 from public.bookings where tenant_id = t.id) then
    return; -- idempotent
  end if;
  for d in -6..4 loop
    foreach hh in array array[10, 13, 16] loop
      i := i + 1;
      select * into svc from public.services
       where tenant_id = t.id and active and duration_minutes < 600
       order by sort offset (i % greatest(1, (select count(*) from public.services where tenant_id = t.id and active and duration_minutes < 600))::int)
       limit 1;
      start := app.local_to_ts(app.local_today(t.timezone) + d, make_time(hh, 0, 0), t.timezone);
      begin
        res := app.create_booking(t, svc.id, start, names[1 + i % 10], '+7900' || lpad((1000000 + i * 7919)::text, 7, '0'),
                                  cars[1 + (i * 3) % 10], '', 'seed-' || p_slug || '-' || i, 'owner', null, true);
      exception when others then
        continue; -- slot already taken by an earlier demo booking
      end;
      bid := (res #>> '{booking,id}')::uuid;
      if d < 0 then
        if i % 7 = 0 then
          update public.bookings set status = 'no_show' where id = bid;
          update public.resource_occupancies set released_at = now() where booking_id = bid;
        elsif i % 9 = 0 then
          perform app.cancel_booking(t.id, bid, 'client', 'Демо: планы изменились');
        else
          update public.bookings set status = 'completed', arrived_at = start, completed_at = start + make_interval(mins => duration_minutes)
           where id = bid;
          insert into public.payments(tenant_id, booking_id, kind, amount_cents, method, idempotency_key, created_at)
          select t.id, bid, 'payment', price_cents + (case when price_is_from then 150000 else 0 end),
                 (array['card', 'cash', 'transfer'])[1 + i % 3], 'seed-pay-' || bid, start + make_interval(mins => duration_minutes)
          from public.bookings where id = bid;
        end if;
      elsif d = 0 and hh = 10 then
        update public.bookings set status = 'arrived', arrived_at = start where id = bid;
      end if;
    end loop;
  end loop;
end;
$$;
`;

const FOOTER = `
drop schema seed_demo cascade;
`;

export function generateSeed(): string {
  const body = DEMO_TENANTS.map((t) => tenantSql(t.slug, t.owner, t.password)).join('\n');
  return `${HEADER}\n${body}\n${FOOTER}`;
}

if (isMain(import.meta.url)) {
  writeFileSync(join(ROOT, 'supabase/seed.sql'), generateSeed());
  log.ok('supabase/seed.sql обновлён');
  // JSON Schema for editor autocompletion in tenants/*/business.json
  const schema = z.toJSONSchema(businessSchema, { io: 'input', unrepresentable: 'any' });
  writeFileSync(join(ROOT, 'schemas/business.schema.json'), JSON.stringify(schema, null, 2) + '\n');
  log.ok('schemas/business.schema.json обновлён');
}
