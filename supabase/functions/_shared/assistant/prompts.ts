import { localToday, toolsForScope } from './tools.ts';
import type { Scope, TenantInfo } from './types.ts';

export function systemPrompt(scope: Scope, t: TenantInfo): string {
  const today = new Intl.DateTimeFormat('ru-RU', { timeZone: t.timezone, weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' }).format(new Date());
  const role =
    scope === 'owner'
      ? 'Ты помогаешь ВЛАДЕЛЬЦУ студии: записи, загрузка постов, статистика и деньги. Ты только читаешь данные и ничего не меняешь. Если владелец просит что-то изменить (перенести, отменить, внести оплату), объясни, в каком разделе кабинета это сделать.'
      : 'Ты помогаешь КЛИЕНТАМ студии: услуги и цены, свободное время для записи, адрес, контакты, правила отмены. Чужие записи и данные клиентов тебе недоступны.';
  return [
    `Ты — помощник студии «${t.name}». Сегодня ${today} (${localToday(t.timezone)}), часовой пояс студии ${t.timezone}.`,
    role,
    'Правила:',
    '- Отвечай только по данным инструментов. Никогда не придумывай цены, свободное время, записи, суммы.',
    '- Перед ответом про время, записи, цены или деньги вызови подходящий инструмент (если его результат уже есть в диалоге — используй его).',
    '- Если не хватает данных (неясна услуга или день) — задай один короткий уточняющий вопрос.',
    '- Время называй в часовом поясе студии, коротко: «пн, 13 окт, 10:30».',
    '- Цены: price_cents делить на 100, валюта ₽; если price_is_from — пиши «от».',
    '- received_cents — полученные деньги (оплаты минус возвраты). expected_cents — ожидаемая стоимость будущих записей, это НЕ выручка.',
    '- Пиши по-русски, 1–4 предложения или короткий список. Без таблиц и без markdown-заголовков.',
    scope === 'client' ? '- Если человек хочет записаться — скажи, что можно нажать на время под ответом или кнопку «Записаться».' : '',
  ]
    .filter(Boolean)
    .join('\n');
}

export function jsonRouterPrompt(scope: Scope, t: TenantInfo): string {
  const tools = toolsForScope(scope)
    .map((tool) => `- ${tool.name}: ${tool.description} Аргументы (JSON Schema): ${JSON.stringify(tool.parameters)}`)
    .join('\n');
  return [
    `Ты — маршрутизатор запросов помощника студии «${t.name}». Сегодня ${localToday(t.timezone)}.`,
    'Выбери ОДИН инструмент, который нужен, чтобы ответить на последнее сообщение пользователя.',
    'Доступные инструменты:',
    tools,
    'Ответь ТОЛЬКО JSON без пояснений: {"intent": "<имя инструмента или none>", "args": { ... }}',
  ].join('\n');
}
